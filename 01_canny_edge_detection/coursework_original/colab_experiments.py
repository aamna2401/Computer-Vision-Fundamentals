def calculate_gradient (fx,fy):
    gradient = np.sqrt(fx**2, fy**2)
    gradient = gradient / gradient.max() * 255
    angle =  np.arctan2(fy, fx)
    theta = angle/math.pi * 180 + 180
    #edge = np.where(gradient>0)
    #gradient[edge] = 0.1
    plt.imshow(gradient,cmap='gray')
    plt.title("Gradient at each pixel")
    plt.savefig(save_path + '/Gradient_at_each_pixel.png')
    plt.show()
    plt.imshow(theta,cmap='gray')
    plt.title("orientation at each pixel")
    plt.savefig(save_path + '/orientation_at _each pixel.png')
    plt.show()
    return gradient, theta

def NMS(gradient, theta):
    img_row, img_col = gradient.shape
    nms_result = np.zeros(gradient.shape)
    for row in range(1, img_row-1):
        for col in range(1, img_col-1):
            direction = theta[row, col]
            
            if (0 <= direction < 22.5) or (157.5 <= direction < 202.5 ) or (337.5 <= direction < 360):
                 gradient[row, col-1] = 0
                 gradient[row, col+1] = 0
            elif (22.5 <= direction < 67.5) or (202.5 <= direction < 247.5 ):
                gradient[row-1, col-1] = 1
                gradient[row+1, col+1] = 1
            elif (67.5 <= direction < 112.5) or (247.5 <= direction < 292.5 ):
                gradient[row-1, col] = 2 
                gradient[row+1, col] = 2
            else:
                gradient[row+1, col-1] = 3 
                gradient[row-1, col+1] = 3
                
            if gradient[row, col] >= 0:
                nms_result[row, col] = gradient[row, col]  
    plt.imshow(nms_result, cmap='gray')
    plt.title("NMS Result") 
    plt.savefig(save_path + '/NMS_Resut.png')
    plt.show()         
    return  nms_result  

def quantized_orientation(nms_result):
  nms_result_rgb =[]
  for i in range(nms_result.shape[0]):
    for j in range(nms_result.shape[1]):
      val = nms_result[i, j]
      if(val==1.0):
        nms_result_rgb.append( (255, 0, 0)  )
      elif(val==2.0):
        nms_result_rgb.append( (0, 255, 0)  )
      elif(val==3.0):
        nms_result_rgb.append( (0, 0, 255)  )
      else:
        nms_result_rgb.append( (0, 0, 0)  )
  nms_result_rgb = np.array(nms_result_rgb).reshape(nms_result.shape[0], nms_result.shape[1], 3) 
  plt.imshow(nms_result_rgb)
  plt.title("quantized_orientation")
  plt.savefig(save_path + '/quantized_orientation.png')
  plt.show()
  return nms_result_rgb

def threshold(image, low, high):
    result = np.zeros(image.shape)
    weak = np.int32(25)
    strong = np.int32(255)
    strong_row, strong_col = np.where(image >= high)
    weak_row, weak_col = np.where((image <= high) & (image >= low))
 
    result[strong_row, strong_col] = strong
    result[weak_row, weak_col] = weak
    plt.imshow(result, cmap='gray')
    plt.title("threshold")
    plt.savefig(save_path + '/threshold_result.png')
    plt.show()
    return result

