def main(img_path, save_path, sigma, t):
  #image reading
  img = img_read(img_path)
  #convert to grayscale
  imgGray = rgb_to_grayscale(img)
  #Filter size
  Gx, Gy = calculate_filter_size(sigma=sigma, T=t)
  #Convlution
  fx, fy = convolution(imgGray,Gx,Gy)
  #gradient calculation
  gradient, theta = calculate_gradient(fx,fy)
  #Non_Maximum_Supression
  nms_result = NMS(gradient, theta)
  #quantized_orientation
  nms_result_rgb = quantized_orientation(nms_result)
  #Threshold
  thresh_result = threshold(nms_result, 0.3, 0.9)
  #Final Step--Hysteresis
  final_edges = hysteresis(thresh_result, weak=100)
  return final_edges

